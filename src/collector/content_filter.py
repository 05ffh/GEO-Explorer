def to_simplified(text: str) -> str:
    """繁→简（t2s），简体输入幂等不变。opencc 缺失时返回原文（降级不阻塞）。"""
    if not text or not _OPENCC_AVAILABLE:
        return text
    return OpenCC("t2s").convert(text)


