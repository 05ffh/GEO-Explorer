def _is_chinese_line(s: str) -> bool:
    """中文为主（剔除非中文行 = 官网/OTA 的日/马/英版本重复）。≥4 个汉字且汉字占比 >25%。"""
    zh = len(_ZH.findall(s))
    return zh >= 4 and zh / max(len(s), 1) > 0.25


def _has_attr(s: str) -> bool:
    t = s.replace("*", "")   # 去 markdown 粗体标记后判属性（"**USD 209**"→"USD 209"）
    return any(kw in t for kw in _ATTR_KEYWORDS) or bool(_CURRENCY.search(t))


def _is_link_cluster(s: str) -> bool:
    """一行含 ≥2 个 markdown 链接 = 导航簇/footer（每页重复，白吃语料预算），丢弃。"""
    return s.count("](") >= 2


def filter_client_facts(raw: str) -> str:
    """原文 → 甲方属性基准事实（行级去噪 + 抽属性 + 去重，高召回）。

    **关键词优先（2026-09-14 修）**：含属性关键词的行**必留**（不拘长短/语言）——OTA 设施列表
    是"每项一行"的短行（室内泳池/健身房/桑拿）、英文距离（Airport 45 公里）、表格容量（宴会厅|1725）
    都是真事实，旧版 len<6/非中文 规则把它们误丢（假阴性 395 行）。
    丢弃：纯链接行 / 下单 UI（整行选择器）/ boilerplate / 不含关键词的短行与非中文行。

    **UI 令牌不误杀事实（2026-09-15 修）**：`间客房/位成人/名儿童` 由"裸子串"改"整行选择器"匹配——
    旧版把"414**间客房**与套房…""最多入住4**位成人**…"当预订框误删（真事实假阴性）。价格行
    （货币代码+金额，如"每2晚由 USD 209 起"）纳入属性优先，中文占比不足也保留。
    """
    seen: set[str] = set()
    out: list[str] = []
    in_opinion = False   # 观点区标记（架构改造 2026-09-17）
    raw = to_simplified(raw or "")   # 繁→简（2026-09-18）：境外 OTA 繁体界面 → 简体，保下游/落地不产繁体
    for line in raw.split("\n"):
        stripped = line.strip()
        if not stripped:
            continue
        # 标题分区：观点区标题 → 后续行整区剔除（含无标记的点评正文）；资料区标题 → 恢复
        h = _MD_HEADING.match(stripped)
        if h:
            if _OPINION_HEADING.search(h.group(1)):
                in_opinion = True
            elif _FACT_HEADING.search(h.group(1)):
                in_opinion = False
            continue   # 标题行本身不入 content_text
        if in_opinion:
            continue
        s = stripped.strip("*->•|+# \t")
        if not s:
            continue
        if _REVIEW_AGG.match(s):   # 点评聚合统计行（"服務品質 (5338)"）→ 观点，非事实
            continue
        if _LINK_ONLY.match(stripped):
            continue
        if _is_link_cluster(s):
            continue
        if _BOOKING_WIDGET.match(s):       # 整行都是人数/房间选择器 → 下单 UI
            continue
        if _BOOKING_UI.search(s) or _BOILERPLATE.search(s):
            continue
        if _UGC_REVIEW.search(s):          # 用户点评（UGC 观点，非甲方事实）→ 不入甲方事实
            continue
        # 高召回：含属性关键词/价格（货币+金额）且含 ≥2 汉字的行必留（OTA 短行设施名"室内泳池"、
        # 英文"Airport 45 公里"、"每2晚由 USD 209 起"都满足）；纯外文关键词行（马来/纯英文重复）丢。
        # 否则须是较长（≥6）中文实质行。
        if _has_attr(s):
            # ¥价格行（"¥70/人"）汉字少也留——价格是事实；纯外文行（CNY 在马来句里）仍丢（2026-10-10）
            if len(_ZH.findall(s)) < 2 and not _CNY_PRICE.search(s.replace("*", "")):
                continue
        elif not (_is_chinese_line(s) and len(s) >= 6):
            continue
        if s in seen:
            continue
        seen.add(s)
        out.append(s)
    return "\n".join(out)
